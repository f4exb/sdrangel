bool
SWGAircraftSettings::isSet(){
    bool isObjectUpdated = false;
    do{
        if(m_removal_mins_isSet){
            isObjectUpdated = true; break;
        }
        if(m_adsb_position_mins_isSet){
            isObjectUpdated = true; break;
        }
        if(m_acars_position_mins_isSet){
            isObjectUpdated = true; break;
        }
        if(m_retention_days_isSet){
            isObjectUpdated = true; break;
        }
        if(m_flight_retention_days_isSet){
            isObjectUpdated = true; break;
        }
        if(m_atc_labels_isSet){
            isObjectUpdated = true; break;
        }
        if(m_atc_callsigns_isSet){
            isObjectUpdated = true; break;
        }
        if(m_display_max_range_on_map_isSet){
            isObjectUpdated = true; break;
        }
        if(m_favour_livery_isSet){
            isObjectUpdated = true; break;
        }
        if(m_display_statistics_isSet){
            isObjectUpdated = true; break;
        }
        if(m_display_chart_isSet){
            isObjectUpdated = true; break;
        }
        if(m_display_coverage_isSet){
            isObjectUpdated = true; break;
        }
        if(m_use_livery_icons_isSet){
            isObjectUpdated = true; break;
        }
        if(m_feed_enabled_isSet){
            isObjectUpdated = true; break;
        }
        if(feed_station_id && *feed_station_id != QString("")){
            isObjectUpdated = true; break;
        }
        if(m_feed_airframes_isSet){
            isObjectUpdated = true; break;
        }
        if(feed_airframes_host && *feed_airframes_host != QString("")){
            isObjectUpdated = true; break;
        }
        if(m_feed_airframes_port_isSet){
            isObjectUpdated = true; break;
        }
        if(m_feed_airframes_tcp_isSet){
            isObjectUpdated = true; break;
        }
        if(m_feed_avdelphi_isSet){
            isObjectUpdated = true; break;
        }
        if(feed_avdelphi_host && *feed_avdelphi_host != QString("")){
            isObjectUpdated = true; break;
        }
        if(m_feed_avdelphi_port_isSet){
            isObjectUpdated = true; break;
        }
        if(m_feed_avdelphi_tcp_isSet){
            isObjectUpdated = true; break;
        }
        if(database_filename && *database_filename != QString("")){
            isObjectUpdated = true; break;
        }
        if(disabled_sources && (disabled_sources->size() > 0)){
            isObjectUpdated = true; break;
        }
        if(notification_settings && (notification_settings->size() > 0)){
            isObjectUpdated = true; break;
        }
        if(title && *title != QString("")){
            isObjectUpdated = true; break;
        }
        if(m_rgb_color_isSet){
            isObjectUpdated = true; break;
        }
        if(m_use_reverse_api_isSet){
            isObjectUpdated = true; break;
        }
        if(reverse_api_address && *reverse_api_address != QString("")){
            isObjectUpdated = true; break;
        }
        if(m_reverse_api_port_isSet){
            isObjectUpdated = true; break;
        }
        if(m_reverse_api_feature_set_index_isSet){
            isObjectUpdated = true; break;
        }
        if(m_reverse_api_feature_index_isSet){
            isObjectUpdated = true; break;
        }
        if(m_workspace_index_isSet){
            isObjectUpdated = true; break;
        }
        if(rollup_state && rollup_state->isSet()){
            isObjectUpdated = true; break;
        }
    }while(false);
    return isObjectUpdated;
}
