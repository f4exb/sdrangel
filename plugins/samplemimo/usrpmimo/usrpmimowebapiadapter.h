#ifndef PLUGINS_SAMPLEMIMO_USRPMIMO_USRPMIMOWEBAPIADAPTER_H_
#define PLUGINS_SAMPLEMIMO_USRPMIMO_USRPMIMOWEBAPIADAPTER_H_

#include "device/devicewebapiadapter.h"
#include "usrpmimosettings.h"

class USRPMIMOWebAPIAdapter : public DeviceWebAPIAdapter
{
public:
    USRPMIMOWebAPIAdapter();
    virtual ~USRPMIMOWebAPIAdapter();

    virtual QByteArray serialize() { return m_settings.serialize(); }
    virtual bool deserialize(const QByteArray& data) { return m_settings.deserialize(data); }

    virtual int webapiSettingsGet(
            SWGSDRangel::SWGDeviceSettings& response,
            QString& errorMessage);

    virtual int webapiSettingsPutPatch(
            bool force,
            const QStringList& deviceSettingsKeys,
            SWGSDRangel::SWGDeviceSettings& response, // query + response
            QString& errorMessage);

private:
    USRPMIMOSettings m_settings;
};

#endif // PLUGINS_SAMPLEMIMO_USRPMIMO_USRPMIMOWEBAPIADAPTER_H_
