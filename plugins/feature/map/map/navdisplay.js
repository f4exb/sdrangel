function ndMouseDown(e) {
    e.preventDefault();
    e.stopPropagation();
    const r = ndCanvas.getBoundingClientRect();
    // Canvas is drawn in a 1000x1000 space, then CSS scaled
    const x = e.offsetX * 1000 / r.width;
    const y = e.offsetY * 1000 / r.height;
    if (panelInClose(x, y)) {
        panelClose("nd", ndCanvas);
        return;
    }
    ndPosX = r.left;
    ndPosY = r.top;
    ndCanvasWidth = r.width;
    ndCanvasHeight = r.height;
    ndDragX = e.clientX;
    ndDragY = e.clientY;
    if ((e.offsetX > 0.95 * ndCanvasWidth) && (e.offsetY > 0.95 * ndCanvasHeight)) {
        ndScale = true;
    } else {
        ndMove = true;
    }
}
function ndMouseUp(e) {
    e.preventDefault();
    e.stopPropagation();
    if (ndMove || ndScale) {
        panelSaveGeometry("nd", ndCanvas);
    }
    ndMove = false;
    ndScale = false;
    ndRestoreDocMouse();
}
function ndMouseMove(e) {
    e.preventDefault();
    e.stopPropagation();
    if (ndMove) {
        ndCanvas.style.position = "absolute";
        ndCanvas.style.left = (ndPosX + e.clientX - ndDragX) + "px";
        ndCanvas.style.top = (ndPosY + e.clientY - ndDragY) + "px";
    } else if (ndScale) {
        const newWidth = ndCanvasWidth + e.clientX - ndDragX;
        const newHeight = ndCanvasHeight + e.clientY - ndDragY;
        const constrainedWidth = Math.max(newWidth, 250);
        const constrainedHeight = Math.max(newHeight, 250);
        ndCanvas.style.width = constrainedWidth + "px";
        ndCanvas.style.height = constrainedHeight + "px";
        drawND(); // Redrawn at the new size, so it stays sharp while resizing
    }
}

function ndMouseLeave(e) {
    if ((ndScale || ndMove) && !ndDocMouseCaptured) {
        ndDocMouseUp = document.onmouseup;
        ndDocMouseMove = document.onmousemove;
        ndDocMouseCaptured = true;
        document.onmouseup = ndMouseUp;
        document.onmousemove = ndMouseMove;
    }
}

function ndRestoreDocMouse() {
    if (ndDocMouseCaptured) {
        document.onmouseup = ndDocMouseUp;
        document.onmousemove = ndDocMouseMove;
        ndDocMouseUp = null;
        ndDocMouseMove = null;
        ndDocMouseCaptured = false;
    }
}
function ndMouseEnter(e) {
    ndRestoreDocMouse();
}

function ndWheel(e) {
    e.preventDefault();
    e.stopPropagation();
    // Wheel up zooms in
    ndSetRange(ndRangeIdx + ((e.deltaY < 0) ? -1 : 1));
}

// ---------------------------------------------------------------------------------
// EFIS control panel - a separate canvas above the ND carrying its controls, in the
// style of the A320 EFIS section of the FCU: a MODE selector, a RANGE selector and
// the overlay pushbuttons (WX, TERR, ARPT, VOR - a lit green bar means on). Moving
// the controls here freed the ND's top right corner for the waypoint information.
// Drawn in a 1000x260 logical space; shares the nd* state it controls.

const efisModeLabels = ["ROSE", "ARC"];
const efisWxRect = { x: 580, y: 30, w: 170, h: 85 };
const efisTerrRect = { x: 770, y: 30, w: 170, h: 85 };
const efisArptRect = { x: 580, y: 145, w: 170, h: 85 };
const efisVorRect = { x: 770, y: 145, w: 170, h: 85 };
const efisModeKnob = { cx: 150, cy: 165, r: 55 };
const efisRangeKnob = { cx: 430, cy: 165, r: 55 };

function efisPrepareCanvas() {
    if ((efisCanvas.clientWidth > 0) && (efisCanvas.clientHeight > 0)) {
        const dpr = window.devicePixelRatio || 1;
        const w = Math.round(efisCanvas.clientWidth * dpr);
        const h = Math.round(efisCanvas.clientHeight * dpr);
        if ((efisCanvas.width !== w) || (efisCanvas.height !== h)) {
            efisCanvas.width = w;
            efisCanvas.height = h;
        }
    }
    const ctx = efisCanvas.getContext("2d");
    ctx.setTransform(efisCanvas.width / 1000, 0, 0, efisCanvas.height / 260, 0, 0);
    return ctx;
}

// A rotary selector: labels on an arc over the knob, the selected one green, with
// the pointer turned to it
function efisDrawKnob(ctx, knob, title, labels, selected) {
    ctx.font = "24px Arial";
    ctx.textAlign = "center";
    ctx.fillStyle = "white";
    // The title sits on the panel's title row unless the knob says otherwise (the RMP's
    // TCAS knob is in the lower half of a taller panel)
    ctx.fillText(title, knob.cx, (knob.titleY !== undefined) ? knob.titleY : 42);

    const n = labels.length;
    for (var i = 0; i < n; i++) {
        const a = (n === 1) ? 0 : (-65 + 130 * i / (n - 1)) * Math.PI / 180;
        ctx.font = "20px Arial";
        ctx.fillStyle = (i === selected) ? greenColor : "#C8C8C8";
        ctx.fillText(labels[i], knob.cx + Math.sin(a) * (knob.r + 32), knob.cy - Math.cos(a) * (knob.r + 32) + 7);
    }

    ctx.fillStyle = "#4A4A55";
    ctx.beginPath();
    ctx.arc(knob.cx, knob.cy, knob.r, 0, 2 * Math.PI);
    ctx.fill();
    ctx.strokeStyle = "#6A6A75";
    ctx.lineWidth = 3;
    ctx.stroke();

    const a = (n === 1) ? 0 : (-65 + 130 * selected / (n - 1)) * Math.PI / 180;
    ctx.strokeStyle = "white";
    ctx.lineWidth = 7;
    ctx.beginPath();
    ctx.moveTo(knob.cx + Math.sin(a) * knob.r * 0.35, knob.cy - Math.cos(a) * knob.r * 0.35);
    ctx.lineTo(knob.cx + Math.sin(a) * knob.r * 0.95, knob.cy - Math.cos(a) * knob.r * 0.95);
    ctx.stroke();
}

// An A320 style pushbutton: dark cap, white legend, and a green bar lit when on
function efisDrawButton(ctx, rect, label, on) {
    ctx.fillStyle = "#26262E";
    ctx.fillRect(rect.x, rect.y, rect.w, rect.h);
    ctx.strokeStyle = "#55555F";
    ctx.lineWidth = 3;
    ctx.strokeRect(rect.x, rect.y, rect.w, rect.h);
    ctx.font = "26px Arial";
    ctx.textAlign = "center";
    ctx.fillStyle = "#C8C8C8";
    ctx.fillText(label, rect.x + rect.w / 2, rect.y + 38);
    if (on) {
        ctx.fillStyle = greenColor;
        ctx.fillRect(rect.x + 30, rect.y + rect.h - 28, rect.w - 60, 14);
    }
}

function drawEFIS() {
    if (efisCanvas === null) {
        return;
    }
    const ctx = efisPrepareCanvas();

    ctx.fillStyle = "#33333C";
    ctx.fillRect(0, 0, 1000, 260);
    ctx.strokeStyle = "#55555F";
    ctx.lineWidth = 4;
    ctx.strokeRect(2, 2, 996, 256);

    efisDrawKnob(ctx, efisModeKnob, "MODE", efisModeLabels, ndMode);
    efisDrawKnob(ctx, efisRangeKnob, "RANGE", ndRanges.map(String), ndRangeIdx);

    efisDrawButton(ctx, efisWxRect, "WX", ndWxEnabled);
    efisDrawButton(ctx, efisTerrRect, "TERR", ndTerrEnabled);
    efisDrawButton(ctx, efisArptRect, "ARPT", ndShowArpt);
    efisDrawButton(ctx, efisVorRect, "VOR", ndShowVor);

    panelDrawClose(ctx);

    efisCheckState();
}

function efisInKnob(x, y, knob) {
    // The clickable area includes the label arc, so clicking a label works too
    const dx = x - knob.cx;
    const dy = y - knob.cy;
    return Math.sqrt(dx * dx + dy * dy) <= knob.r + 55;
}

var efisMove = false;
var efisScale = false;
var efisPosX = 0;
// Where the cursor was when the drag started, so each move places the panel
// absolutely from it rather than accumulating deltas
var efisDragX = 0;
var efisDragY = 0;
var efisPosY = 0;
var efisWidth = 0;
var efisHeight = 0;

function efisMouseDown(e) {
    e.preventDefault();
    e.stopPropagation();
    const r = efisCanvas.getBoundingClientRect();
    const x = e.offsetX * 1000 / r.width;
    const y = e.offsetY * 260 / r.height;
    if (panelInClose(x, y)) {
        panelClose("efis", efisCanvas);
        return;
    }
    if (efisInKnob(x, y, efisModeKnob)) {
        // Left half turns one way, right half the other - with two positions,
        // either just swaps
        ndMode = (ndMode === 1) ? 0 : 1;
    } else if (efisInKnob(x, y, efisRangeKnob)) {
        ndSetRange(ndRangeIdx + ((x < efisRangeKnob.cx) ? -1 : 1));
    } else if (ndInRect(x, y, efisWxRect)) {
        ndWxEnabled = !ndWxEnabled;
        if (ndWxEnabled) {
            ndTerrEnabled = false; // WX and TERR share the display, as on the aircraft
        }
    } else if (ndInRect(x, y, efisTerrRect)) {
        ndTerrEnabled = !ndTerrEnabled;
        if (ndTerrEnabled) {
            ndWxEnabled = false;
        }
    } else if (ndInRect(x, y, efisArptRect)) {
        ndShowArpt = !ndShowArpt;
    } else if (ndInRect(x, y, efisVorRect)) {
        ndShowVor = !ndShowVor;
    } else {
        efisPosX = r.left;
        efisPosY = r.top;
        efisWidth = r.width;
        efisHeight = r.height;
    efisDragX = e.clientX;
    efisDragY = e.clientY;
        // A fixed 25px corner, not a fraction: 5% of this short panel was unhittable
        if ((e.offsetX > efisWidth - 25) && (e.offsetY > efisHeight - 25)) {
            efisScale = true;
        } else {
            efisMove = true;
        }
        return;
    }
    drawND();
    drawEFIS();
}
function efisMouseUp(e) {
    e.preventDefault();
    e.stopPropagation();
    if (efisMove || efisScale) {
        panelSaveGeometry("efis", efisCanvas);
    }
    efisMove = false;
    efisScale = false;
    efisRestoreDocMouse();
}
function efisMouseMove(e) {
    e.preventDefault();
    e.stopPropagation();
    if (efisMove) {
        efisCanvas.style.position = "absolute";
        efisCanvas.style.left = (efisPosX + e.clientX - efisDragX) + "px";
        efisCanvas.style.top = (efisPosY + e.clientY - efisDragY) + "px";
    } else if (efisScale) {
        const newWidth = efisWidth + e.clientX - efisDragX;
        const newHeight = efisHeight + e.clientY - efisDragY;
        efisCanvas.style.width = Math.max(newWidth, 250) + "px";
        efisCanvas.style.height = Math.max(newHeight, 65) + "px";
        drawEFIS();
    }
}
// The wheel turns whichever rotary it is over; anywhere else it works the range,
// matching the wheel's behaviour over the ND itself. Wheel up turns the selector
// clockwise - the way the knob would move under a finger - which steps to the next
// label to the right, so up is towards the longer ranges
function efisWheel(e) {
    e.preventDefault();
    e.stopPropagation();
    const r = efisCanvas.getBoundingClientRect();
    const x = e.offsetX * 1000 / r.width;
    const y = e.offsetY * 260 / r.height;
    const step = (e.deltaY < 0) ? 1 : -1;
    if (efisInKnob(x, y, efisModeKnob)) {
        ndMode = (ndMode === 1) ? 0 : 1;
        drawND();
    } else {
        ndSetRange(ndRangeIdx + step);
    }
    drawEFIS();
}

// A drag chases a window that lags the cursor, so the cursor is forever escaping the
// canvas - especially one this short. Hand the drag to document-level handlers when
// it leaves, and take it back when it returns, exactly as the ND does
var efisDocMouseMove = null;
var efisDocMouseUp = null;
var efisDocMouseCaptured = false;

function efisMouseLeave(e) {
    if ((efisScale || efisMove) && !efisDocMouseCaptured) {
        efisDocMouseUp = document.onmouseup;
        efisDocMouseMove = document.onmousemove;
        efisDocMouseCaptured = true;
        document.onmouseup = efisMouseUp;
        document.onmousemove = efisMouseMove;
    }
}

function efisRestoreDocMouse() {
    if (efisDocMouseCaptured) {
        document.onmouseup = efisDocMouseUp;
        document.onmousemove = efisDocMouseMove;
        efisDocMouseUp = null;
        efisDocMouseMove = null;
        efisDocMouseCaptured = false;
    }
}

function efisMouseEnter(e) {
    efisRestoreDocMouse();
}

// Null in a page (such as a test harness) without the panel
const efisCanvas = document.getElementById('efisCanvas');
if (efisCanvas !== null) {
    efisCanvas.onmousedown = efisMouseDown;
    efisCanvas.onmouseup = efisMouseUp;
    efisCanvas.onmousemove = efisMouseMove;
    efisCanvas.onmouseleave = efisMouseLeave;
    efisCanvas.onmouseenter = efisMouseEnter;
    efisCanvas.onwheel = efisWheel;
}

