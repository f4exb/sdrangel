// ---------------------------------------------------------------------------------
// The EFIS control settings - what the knobs and pushbuttons are set to - are kept in
// the Map's settings so they survive a restart. Rather than reporting from each of the
// scattered places that change them (knob clicks, button clicks, the wheel, the RMP's
// TCAS selector), the drawing passes compare a signature of the lot and report a
// change: one place, and nothing can quietly bypass it

var efisStateSignature;
// Nothing is saved until the GUI has sent what it had, so the stored settings are not
// overwritten by the defaults this page starts with
var efisStateReady = false;

function efisState() {
    return {
        mode: ndMode, range: ndRangeIdx,
        wx: ndWxEnabled, terr: ndTerrEnabled,
        arpt: ndShowArpt, vor: ndShowVor,
        tcas: ndTcasFilterIdx
    };
}

function efisCheckState() {
    const signature = JSON.stringify(efisState());
    if (signature === efisStateSignature) {
        return;
    }
    const first = (efisStateSignature === undefined);
    efisStateSignature = signature;
    if (efisStateReady && !first) {
        panelSend(Object.assign({ event: "efisState" }, efisState()));
    }
}

// From the GUI, on connecting: the settings as they were left
function setEFISState(s) {
    if (s !== undefined)
    {
        if ((s.mode === 0) || (s.mode === 1)) {
            ndMode = s.mode;
        }
        if ((s.range >= 0) && (s.range < ndRanges.length)) {
            ndRangeIdx = s.range;
        }
        if ((s.tcas >= 0) && (s.tcas <= 3)) {
            ndTcasFilterIdx = s.tcas;
        }
        if (s.wx !== undefined) {
            ndWxEnabled = (s.wx === true);
        }
        if (s.terr !== undefined) {
            ndTerrEnabled = (s.terr === true);
        }
        if (s.arpt !== undefined) {
            ndShowArpt = (s.arpt === true);
        }
        if (s.vor !== undefined) {
            ndShowVor = (s.vor === true);
        }
    }
    efisStateSignature = JSON.stringify(efisState());
    efisStateReady = true;
}

