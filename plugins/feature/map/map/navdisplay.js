// Distance in NM from own position to the arrival airport - the waypoint named as the
// arrival, or failing that the last placed waypoint. undefined when it cannot be known.
function ndDistanceToArrival() {
    if ((ndFlightPlan === undefined) || (ndFlightPlan.wpts === undefined)
        || (ndLat === undefined) || (ndLon === undefined)) {
        return undefined;
    }
    var arrival;
    for (const wp of ndFlightPlan.wpts) {
        if ((wp.lat === undefined) || (wp.lon === undefined)) {
            continue;
        }
        if (wp.n === ndFlightPlan.arr) {
            arrival = wp;
            break;
        }
        arrival = wp; // Last placed waypoint, unless the arrival itself is found
    }
    if (arrival === undefined) {
        return undefined;
    }
    const dN = (arrival.lat - ndLat) * 60.0;
    const dE = (arrival.lon - ndLon) * 60.0 * Math.cos(ndLat * Math.PI / 180.0);
    return Math.sqrt(dN * dN + dE * dE);
}

// The runway an approach serves, from the approach as filed - ILSY01R gives 01R.
// undefined when the name does not end in one, as a plain RNAV or VOR approach may not.
function ndApproachRunway(approach) {
    if (approach === undefined) {
        return undefined;
    }
    const match = approach.match(/([0-9]{2}[LRC]?)$/);
    return match ? match[1] : undefined;
}

// Arrival approach/runway annunciator, top middle - e.g. "ILSY 01R" - shown when the
// aircraft is flying an approach, or when it is within 250 NM of the arrival airport.
//
// Note that the PFD's G/S and LOC are not two independent facts: both are decoded from
// the single approach-mode bit of the ADS-B target state and status message, and which
// of them the PFD shows depends only on whether VNAV or LNAV masks it (see
// adsbdemodtrackerdecode.cpp). So either one on its own means "flying an approach", and
// testing for both would miss the aircraft that also report LNAV or VNAV.
function ndDrawApproach(ctx) {
    const approaching = (ndVerticalMode === 3) || (ndLateralMode === 2);
    const app = (ndFlightPlan !== undefined) ? ndFlightPlan.app : undefined;
    const rwy = (ndFlightPlan !== undefined) ? ndFlightPlan.rwy : undefined;
    var text;
    if (approaching)
    {
        // Approach mode with a glideslope is an ILS, whatever was filed - so an approach
        // filed as something else is named by its runway rather than by its own name,
        // which would contradict what the aircraft is actually flying. A filed ILS keeps
        // its full name, since the variant letter of an ILSY is worth having.
        const runway = ndApproachRunway(app) || rwy;
        if ((app !== undefined) && app.startsWith("ILS")) {
            text = app.replace(/([0-9]{2}[LRC]?)$/, " $1");
        } else if (runway !== undefined) {
            text = "ILS " + runway;
        } else {
            // No flight plan, or one that never named a runway. Most aircraft seen on
            // approach here are in that position, so this is the common case rather than
            // an edge one, and the annunciator still says what is being flown.
            text = "ILS APPR";
        }
    }
    else
    {
        if (app !== undefined) {
            // The approach as filed usually ends in the runway it serves - ILSY01R -
            // so space it off for readability
            text = app.replace(/([0-9]{2}[LRC]?)$/, " $1");
        } else if (rwy !== undefined) {
            text = "RWY " + rwy;
        } else {
            return;
        }
        const distance = ndDistanceToArrival();
        if ((distance === undefined) || (distance > 250)) {
            return;
        }
    }
    ctx.fillStyle = "white";
    ctx.font = "28px Arial";
    ctx.textAlign = "center";
    ctx.fillText(text, 500, 38);
}


// Match the canvas backing store to the size it is displayed at, so text stays sharp
// however the window is resized - a fixed backing store scaled by CSS goes soft.
// Drawing code stays in the 1000x1000 logical space via the transform.
function ndPrepareCanvas() {
    // clientWidth/Height rather than getBoundingClientRect(), so the border is not
    // included in the drawn area
    if ((ndCanvas.clientWidth > 0) && (ndCanvas.clientHeight > 0)) {
        const dpr = window.devicePixelRatio || 1;
        const w = Math.round(ndCanvas.clientWidth * dpr);
        const h = Math.round(ndCanvas.clientHeight * dpr);
        if ((ndCanvas.width !== w) || (ndCanvas.height !== h)) {
            ndCanvas.width = w;
            ndCanvas.height = h;
        }
    }
    const ctx = ndCanvas.getContext("2d");
    ctx.setTransform(ndCanvas.width / 1000, 0, 0, ndCanvas.height / 1000, 0, 0);
    return ctx;
}

function drawND() {
    const ctx = ndPrepareCanvas();
    const geom = ndGeometry();
    const ppnm = geom.radius / ndRanges[ndRangeIdx];

    ctx.fillStyle = "black";
    ctx.fillRect(0, 0, 1000, 1000);

    // Map layers, clipped to the compass area
    ctx.save();
    ctx.beginPath();
    ctx.arc(geom.refX, geom.refY, geom.radius, 0, 2 * Math.PI);
    ctx.clip();
    if ((ndLat !== undefined) && (ndLon !== undefined)) {
        ndDrawTerrain(ctx, geom, ppnm);
        ndDrawWeather(ctx, geom, ppnm);
        if (ndShowVor) {
            ndDrawNavAids(ctx, geom, ppnm);
        }
        if (ndShowArpt) {
            ndDrawAirports(ctx, geom, ppnm);
        }
        ndDrawFlightPlan(ctx, geom, ppnm);
        ndDrawTraffic(ctx, geom, ppnm);
    }
    ctx.restore();

    ndDrawRangeRings(ctx, geom);
    ndDrawCompass(ctx, geom);
    ndDrawTrack(ctx, geom);
    ndDrawSelectedHeading(ctx, geom);
    ndDrawAircraftSymbol(ctx, geom);
    ndDrawData(ctx);
    ndDrawActiveWaypointInfo(ctx);
    ndDrawApproach(ctx);

    panelDrawClose(ctx);

    // The ND's own wheel changes range, so its settings are checked here too
    efisCheckState();
}

