// Traffic advisories. TCAS II declares a TA when an intruder is within the range
// threshold (DMOD) or will reach closest approach within tau seconds, AND is within
// the altitude threshold or will be within tau seconds. The thresholds step up with
// own altitude (sensitivity level). Own altitude here is barometric - there is no
// AGL - so the lowest levels are approximate. Resolution advisories are NOT computed:
// red only ever comes from an RA the aircraft actually broadcast

const ndTaLevels = [ // Sensitivity levels, from the lowest own altitude up
    { below: 1000, tau: 20, dmod: 0.30, zthr: 850 },
    { below: 2350, tau: 25, dmod: 0.33, zthr: 850 },
    { below: 5000, tau: 30, dmod: 0.48, zthr: 850 },
    { below: 10000, tau: 40, dmod: 0.75, zthr: 850 },
    { below: 20000, tau: 45, dmod: 1.0, zthr: 850 },
    { below: 42000, tau: 48, dmod: 1.3, zthr: 850 },
    { below: Infinity, tau: 48, dmod: 1.3, zthr: 1200 }
];
const ndTaHoldMs = 8000;      // A TA persists this long after its conditions last held
const ndTaForgetMs = 30000;   // Targets not reported for this long are dropped
// Mode S address (lower case) -> {ta, since, lastMet, seen}
var ndAdvisories = new Map();

function ndTaLevel(altitude) {
    for (const level of ndTaLevels) {
        if (altitude < level.below) {
            return level;
        }
    }
    return ndTaLevels[ndTaLevels.length - 1];
}

// North/east offset of a position from own aircraft, in NM (same approximation as
// ndProject, which needs the draw geometry so is not used here)
function ndRangeBearing(lat, lon) {
    const dN = (lat - ndLat) * 60.0;
    const dE = (lon - ndLon) * 60.0 * Math.cos(ndLat * Math.PI / 180.0);
    return { dN: dN, dE: dE, dist: Math.sqrt(dN * dN + dE * dE) };
}

function ndVelocity(gs, trk) {
    if ((gs === undefined) || (trk === undefined)) {
        return undefined;
    }
    const a = trk * Math.PI / 180.0;
    return { n: gs * Math.cos(a), e: gs * Math.sin(a) };
}

function ndIcaoKey(icao) {
    return String(icao).toLowerCase();
}

function ndUpdateAdvisories() {
    const now = Date.now();
    if ((ndLat === undefined) || (ndLon === undefined) || (ndAltitude === undefined) || (ndTcasMode === 1)) {
        ndAdvisories.clear(); // Nothing is being scanned for
        return;
    }
    const level = ndTaLevel(ndAltitude);
    const ownV = ndVelocity(ndGroundspeed, (ndTrack !== undefined) ? ndTrack : ndHeading);
    const threatKey = (ndThreatIcao !== undefined) ? ndIcaoKey(ndThreatIcao) : undefined;
    var announce = false;

    for (const t of ndTraffic) {
        if ((t.icao === undefined) || (t.lat === undefined) || (t.lon === undefined) || (t.altFt === undefined)) {
            continue; // Cannot be tracked between updates, or has no altitude to test
        }
        const key = ndIcaoKey(t.icao);
        const g = ndRangeBearing(t.lat, t.lon);

        // Range test: inside DMOD, or closing fast enough to get there within tau.
        // Without velocities the closure is unknown and only DMOD counts
        var rangeMet = g.dist <= level.dmod;
        const tv = ndVelocity(t.gs, t.trk);
        if (!rangeMet && (ownV !== undefined) && (tv !== undefined) && (g.dist > 0)) {
            // Range rate: the intruder's velocity relative to own, along the line of
            // sight. Negative is closing
            const rdot = ((tv.n - ownV.n) * g.dN + (tv.e - ownV.e) * g.dE) / g.dist;
            if (rdot < -1) {
                rangeMet = (g.dist / -rdot) * 3600 <= level.tau;
            }
        }

        var met = false;
        if (rangeMet) {
            const dz = t.altFt - ndAltitude;
            met = Math.abs(dz) <= level.zthr;
            if (!met && (t.vs !== undefined) && (ndVerticalSpeed !== undefined)) {
                const dzRate = t.vs - ndVerticalSpeed; // ft/min, converging when it reduces |dz|
                if (((dz > 0) && (dzRate < 0)) || ((dz < 0) && (dzRate > 0))) {
                    met = (Math.abs(dz) / Math.abs(dzRate)) * 60 <= level.tau;
                }
            }
        }

        var a = ndAdvisories.get(key);
        if (a === undefined) {
            a = { ta: false, since: 0, lastMet: 0, seen: now };
            ndAdvisories.set(key, a);
        }
        a.seen = now;
        if (met) {
            a.lastMet = now;
            if (!a.ta) {
                a.ta = true;
                a.since = now;
                // "Traffic, traffic" once as each TA is raised - but not for the RA
                // threat, whose RA aurals take priority
                if (key !== threatKey) {
                    announce = true;
                }
            }
        } else if (a.ta && (now - a.lastMet > ndTaHoldMs)) {
            a.ta = false;
        }
    }

    for (const [key, a] of ndAdvisories) {
        if (now - a.seen > ndTaForgetMs) {
            ndAdvisories.delete(key);
        }
    }

    // No TA aural during an RA, below the TCAS inhibit height, or when neither the ND
    // nor the PFD (which arms TCAS on its FMA from these advisories) is displayed
    const visible = function (canvas) {
        return (canvas !== undefined) && (canvas !== null) && !canvas.hasAttribute("hidden");
    };
    const shown = visible(document.getElementById("ndCanvas")) || visible(document.getElementById("pfdCanvas"));
    if (announce && !(ndTcasRA & 1) && !tcasInhibited && shown) {
        pfdPlayAudio("traffic.wav");
    }
}

// Whether any traffic advisory is current - the PFD arms TCAS on its FMA from this
function ndHasTA() {
    for (const a of ndAdvisories.values()) {
        if (a.ta) {
            return true;
        }
    }
    return false;
}

function ndIsTA(t) {
    if (t.icao === undefined) {
        return false;
    }
    const a = ndAdvisories.get(ndIcaoKey(t.icao));
    return (a !== undefined) && a.ta;
}

function ndDrawTraffic(ctx, geom, ppnm) {
    if ((ndLat === undefined) || (ndLon === undefined)) {
        return;
    }
    if (ndTcasMode === 1) {
        return; // TCAS STANDBY: nothing is being scanned for, so nothing is shown
    }
    const range = ndRanges[ndRangeIdx];

    // Project and classify everything in range first, so the EFIS TCAS filter can
    // rank as well as cut
    var targets = [];
    for (const t of ndTraffic) {
        if ((t.lat === undefined) || (t.lon === undefined)) {
            continue;
        }
        var p = ndProject(t.lat, t.lon, geom, ppnm);
        var rel;
        if ((ndAltitude !== undefined) && (t.altFt !== undefined)) {
            rel = Math.round((t.altFt - ndAltitude) / 100);
        }
        // The aircraft an active resolution advisory is against - never filtered out
        const threat = (ndTcasRA & 1) && (ndThreatIcao !== undefined) && (t.icao !== undefined)
            && (String(t.icao).toLowerCase() === String(ndThreatIcao).toLowerCase());
        const ta = !threat && ndIsTA(t);
        if (p.dist > range) {
            if (!(threat || ta)) {
                continue;
            }
            // Advisory traffic beyond the selected range is still shown, clamped to
            // the edge of the rose along its bearing - the rose clip then leaves the
            // half symbol the real display draws
            const k = range / p.dist;
            p = { x: geom.refX + (p.x - geom.refX) * k, y: geom.refY + (p.y - geom.refY) * k, dist: p.dist };
        }
        targets.push({ t: t, p: p, rel: rel, threat: threat, ta: ta });
    }

    // The EFIS TCAS selector: THRT keeps the 8 nearest within +-2700 ft, ALL keeps
    // everything, ABV -2700..+7000 ft, BLW -7000..+2700 ft. Relative altitude is in
    // hundreds of feet here. Advisory traffic is never cut
    const f = ndTcasFilterIdx;
    if (f !== 1) {
        targets = targets.filter(function (e) {
            if (e.threat || e.ta) {
                return true;
            }
            if (e.rel === undefined) {
                return false; // Cannot be classified against an altitude band
            }
            if (f === 0) {
                return Math.abs(e.rel) <= 27;
            }
            if (f === 2) {
                return (e.rel >= -27) && (e.rel <= 70);
            }
            return (e.rel >= -70) && (e.rel <= 27);
        });
        if (f === 0) {
            const rank = function (e) { return e.threat ? 0 : (e.ta ? 1 : 2); };
            targets.sort(function (a, b) {
                if (rank(a) !== rank(b)) {
                    return rank(a) - rank(b);
                }
                return a.p.dist - b.p.dist;
            });
            targets = targets.slice(0, 8);
        }
    }

    ctx.font = "24px Arial";
    for (const e of targets) {
        const t = e.t;
        const p = e.p;
        const rel = e.rel;
        const threat = e.threat;
        // Proximate traffic (within 6 NM and 1200 ft) is a filled diamond
        const proximate = (p.dist <= 6) && (rel !== undefined) && (Math.abs(rel) <= 12);
        var color = "white";
        if (threat) {
            // Resolution advisory: filled red square
            color = redColor;
            ctx.fillStyle = color;
            ctx.fillRect(p.x - 13, p.y - 13, 26, 26);
        } else if (e.ta) {
            // Traffic advisory: filled yellow circle
            color = yellowColor;
            ctx.fillStyle = color;
            ctx.beginPath();
            ctx.arc(p.x, p.y, 14, 0, 2 * Math.PI);
            ctx.fill();
        } else {
            ctx.strokeStyle = "white";
            ctx.fillStyle = "white";
            ctx.lineWidth = 3;
            ctx.beginPath();
            ctx.moveTo(p.x, p.y - 16);
            ctx.lineTo(p.x + 12, p.y);
            ctx.lineTo(p.x, p.y + 16);
            ctx.lineTo(p.x - 12, p.y);
            ctx.closePath();
            if (proximate) {
                ctx.fill();
            } else {
                ctx.stroke();
            }
        }
        ctx.fillStyle = color;
        if (rel !== undefined) {
            ctx.textAlign = "center";
            const text = (rel >= 0 ? "+" : "-") + pad(Math.abs(rel), 2);
            const textY = (rel >= 0) ? p.y - 26 : p.y + 42;
            ctx.fillText(text, p.x, textY);
            if ((t.vs !== undefined) && (Math.abs(t.vs) > 500)) {
                ctx.fillText(t.vs > 0 ? "\u2191" : "\u2193", p.x + 40, textY);
            }
        }
    }
}

