// 32x32x32 quantized RGB -> NEXRAD RGBA, built once by nearest-colour search over
// the Universal Blue entries (a few tens of ms, on first use)
var ndWxLut = null;

function ndWxBuildLut() {
    ndWxLut = new Uint8Array(32 * 32 * 32 * 4);
    const entries = ndWxUB.length / 3;
    for (var ri = 0; ri < 32; ri++) {
        for (var gi = 0; gi < 32; gi++) {
            for (var bi = 0; bi < 32; bi++) {
                const r = ri * 8 + 4;
                const g = gi * 8 + 4;
                const b = bi * 8 + 4;
                var best = 0;
                var bestDist = Infinity;
                for (var e = 0; e < entries; e++) {
                    const dr = r - ndWxUB[e * 3];
                    const dg = g - ndWxUB[e * 3 + 1];
                    const db = b - ndWxUB[e * 3 + 2];
                    const dist = dr * dr + dg * dg + db * db;
                    if (dist < bestDist) {
                        bestDist = dist;
                        best = e;
                    }
                }
                const li = ((ri << 10) | (gi << 5) | bi) * 4;
                ndWxLut[li] = ndWxNX[best * 4];
                ndWxLut[li + 1] = ndWxNX[best * 4 + 1];
                ndWxLut[li + 2] = ndWxNX[best * 4 + 2];
                ndWxLut[li + 3] = ndWxNX[best * 4 + 3];
            }
        }
    }
}

function ndWxRecolour(image) {
    const c = document.createElement("canvas");
    c.width = image.naturalWidth;
    c.height = image.naturalHeight;
    const cctx = c.getContext("2d", { willReadFrequently: true });
    cctx.drawImage(image, 0, 0);
    var data;
    try {
        data = cctx.getImageData(0, 0, c.width, c.height);
    } catch (e) {
        // Cross-origin without CORS: draw the tile as it came rather than not at all
        console.log("Weather tile pixels blocked, drawing unrecoloured: " + e);
        return image;
    }
    if (ndWxLut === null) {
        ndWxBuildLut();
    }
    const px = data.data;
    for (var i = 0; i < px.length; i += 4) {
        const a = px[i + 3];
        if (a === 0) {
            continue;
        }
        const li = (((px[i] >> 3) << 10) | ((px[i + 1] >> 3) << 5) | (px[i + 2] >> 3)) * 4;
        px[i] = ndWxLut[li];
        px[i + 1] = ndWxLut[li + 1];
        px[i + 2] = ndWxLut[li + 2];
        // The NEXRAD alpha (drizzle is transparent), faded by the tile's own edges
        px[i + 3] = (ndWxLut[li + 3] * a) / 255;
    }
    cctx.putImageData(data, 0, 0);
    return c;
}

function ndDrawWeather(ctx, geom, ppnm) {
    if (!ndWxEnabled || (ndWxPath === undefined) || (ndLat === undefined) || (ndLon === undefined)) {
        return;
    }
    const cosLat = Math.cos(ndLat * Math.PI / 180);
    // 512 px tiles, and at most zoom 7: RainViewer's radar composite serves a "not
    // supported" placeholder beyond that (probed empirically - the 256 px tiles stop
    // at 7 too, so 512 is simply twice the resolution for the same limit)
    const tileSize = 512;
    // Ground distance per tile pixel at zoom z is 21600 * cos(lat) / (tileSize * 2^z) NM
    var z = Math.round(Math.log2(ppnm * 21600 * cosLat / tileSize));
    z = Math.max(2, Math.min(7, z));
    const n = Math.pow(2, z);
    // Own position in mercator pixel space at this zoom
    const mx = (ndLon + 180) / 360 * n * tileSize;
    const latRad = ndLat * Math.PI / 180;
    const my = (1 - Math.log(Math.tan(latRad) + 1 / Math.cos(latRad)) / Math.PI) / 2 * n * tileSize;
    const scale = ppnm * 21600 * cosLat / (tileSize * n); // Canvas px per mercator px
    const radiusMerc = geom.radius / scale;
    const tx0 = Math.floor((mx - radiusMerc) / tileSize);
    const tx1 = Math.floor((mx + radiusMerc) / tileSize);
    const ty0 = Math.max(0, Math.floor((my - radiusMerc) / tileSize));
    const ty1 = Math.min(n - 1, Math.floor((my + radiusMerc) / tileSize));

    ctx.save();
    // Mercator y already increases southward, so north-up content drops straight in;
    // this rotation turns it heading-up, exactly matching ndProject()
    ctx.translate(geom.refX, geom.refY);
    ctx.rotate(-ndReferenceHeading() * Math.PI / 180);
    ctx.globalAlpha = 0.85;
    for (var ty = ty0; ty <= ty1; ty++) {
        for (var tx = tx0; tx <= tx1; tx++) {
            const wrapped = ((tx % n) + n) % n; // Antimeridian
            // The colour scheme segment is ignored by the server nowadays - every
            // tile comes back Universal Blue and is recoloured to NEXRAD by
            // ndWxRecolour() as it loads
            const url = "https://tilecache.rainviewer.com/" + ndWxPath + "/" + tileSize + "/" + z + "/" + wrapped + "/" + ty + "/6/1_1.png";
            const img = ndWxTile(url);
            if (img) {
                ctx.drawImage(img, (tx * tileSize - mx) * scale, (ty * tileSize - my) * scale, tileSize * scale, tileSize * scale);
            }
        }
    }
    ctx.globalAlpha = 1.0;
    ctx.restore();
}

function ndTerrTile(url) {
    var img = ndTerrTiles.get(url);
    if (img === undefined) {
        if (ndTerrTiles.size > 256) {
            ndTerrTiles.clear();
        }
        img = new Image();
        img.crossOrigin = "anonymous"; // Required: the pixels are read back
        img.onload = function () { ndTerrGen++; };
        img.src = url;
        ndTerrTiles.set(url, img);
    }
    return (img.complete && (img.naturalWidth > 0)) ? img : undefined;
}

// Composite the covering tiles north-up into an offscreen canvas and recolour each
// pixel by its elevation relative to the aircraft - the EGPWS bands: solid red well
// above the aircraft, dithered red/amber around it, green below, black far below
function ndTerrComposite(mx, my, radiusMerc, z, n, tileSize, altFt) {
    const D = 512; // Composite resolution; the blocky look is authentic
    const off = document.createElement("canvas");
    off.width = D;
    off.height = D;
    const octx = off.getContext("2d", { willReadFrequently: true });
    // Nearest-neighbour: smoothing would interpolate the ENCODED values, and an
    // average of two Terrarium pixels is not the elevation of anything
    octx.imageSmoothingEnabled = false;
    const k = D / (2 * radiusMerc);
    const tx0 = Math.floor((mx - radiusMerc) / tileSize);
    const tx1 = Math.floor((mx + radiusMerc) / tileSize);
    const ty0 = Math.max(0, Math.floor((my - radiusMerc) / tileSize));
    const ty1 = Math.min(n - 1, Math.floor((my + radiusMerc) / tileSize));
    for (var ty = ty0; ty <= ty1; ty++) {
        for (var tx = tx0; tx <= tx1; tx++) {
            const wrapped = ((tx % n) + n) % n;
            const img = ndTerrTile(ndTerrainURL + "/" + z + "/" + wrapped + "/" + ty + ".png");
            if (img) {
                octx.drawImage(img, (tx * tileSize - (mx - radiusMerc)) * k, (ty * tileSize - (my - radiusMerc)) * k, tileSize * k, tileSize * k);
            }
        }
    }
    var data;
    try {
        data = octx.getImageData(0, 0, D, D);
    } catch (e) {
        console.log("Terrain tiles blocked: the tile server must send Access-Control-Allow-Origin: * (" + e + ")");
        return undefined;
    }
    const px = data.data;
    for (var y = 0; y < D; y++) {
        for (var x = 0; x < D; x++) {
            const i = (y * D + x) * 4;
            var r = 0, g = 0, b = 0, a = 0;
            if (px[i + 3] !== 0) { // Alpha 0 is ocean, or a tile not yet loaded
                const elevFt = ((px[i] << 8) + px[i + 1] - 32768) * 3.28084;
                const d = elevFt - altFt;
                const dither2 = ((x ^ y) & 1) === 0;                    // 50%
                const dither4 = ((x & 1) === 0) && ((y & 1) === 0);     // 25%
                if (d > 2000) {
                    r = 252; g = 40; b = 40; a = 255;                   // Solid red
                } else if ((d > 1000) && dither2) {
                    r = 252; g = 40; b = 40; a = 255;
                } else if ((d > -500) && (d <= 1000) && dither2) {
                    r = 254; g = 214; b = 48; a = 255;                  // Amber
                } else if ((d > -1000) && (d <= -500) && dither4) {
                    r = 254; g = 214; b = 48; a = 255;
                } else if ((d > -2000) && (d <= -1000) && dither2) {
                    r = 40; g = 180; b = 60; a = 255;                   // Green
                } else if ((d <= -2000) && (elevFt > 100) && dither4) {
                    r = 30; g = 130; b = 50; a = 255;
                }
            }
            px[i] = r;
            px[i + 1] = g;
            px[i + 2] = b;
            px[i + 3] = a;
        }
    }
    octx.putImageData(data, 0, 0);
    return off;
}

function ndDrawTerrain(ctx, geom, ppnm) {
    if (!ndTerrEnabled || (ndTerrainURL === undefined) || (ndLat === undefined)
        || (ndLon === undefined) || (ndAltitude === undefined)) {
        return;
    }
    const cosLat = Math.cos(ndLat * Math.PI / 180);
    const tileSize = 512;
    // Zoom 6 at 512 px is about the native resolution of the GLOBE data
    var z = Math.round(Math.log2(ppnm * 21600 * cosLat / tileSize));
    z = Math.max(0, Math.min(6, z));
    const n = Math.pow(2, z);
    const mx = (ndLon + 180) / 360 * n * tileSize;
    const latRad = ndLat * Math.PI / 180;
    const my = (1 - Math.log(Math.tan(latRad) + 1 / Math.cos(latRad)) / Math.PI) / 2 * n * tileSize;
    const scale = ppnm * 21600 * cosLat / (tileSize * n);
    const radiusMerc = geom.radius / scale;

    // The per-pixel recolour runs only when the aircraft has moved an eighth of the
    // radius, changed altitude band, the range/zoom changed, or a tile arrived
    const key = z + "," + Math.round(mx * 8 / radiusMerc) + "," + Math.round(my * 8 / radiusMerc)
        + "," + Math.round(ndAltitude / 200) + "," + ndTerrGen;
    if (key !== ndTerrKey) {
        ndTerrKey = key;
        ndTerrCanvas = ndTerrComposite(mx, my, radiusMerc, z, n, tileSize, ndAltitude);
    }
    if (ndTerrCanvas) {
        ctx.save();
        ctx.translate(geom.refX, geom.refY);
        ctx.rotate(-ndReferenceHeading() * Math.PI / 180);
        ctx.imageSmoothingEnabled = false;
        ctx.drawImage(ndTerrCanvas, -geom.radius, -geom.radius, 2 * geom.radius, 2 * geom.radius);
        ctx.restore();
    }
}

// VORs (VOR, VOR-DME, VORTAC) as the conventional hexagon with a centre dot, in
// white, with the ident alongside
function ndDrawNavAids(ctx, geom, ppnm) {
    if ((ndLat === undefined) || (ndLon === undefined) || (ndNavAids.length === 0)) {
        return;
    }
    const range = ndRanges[ndRangeIdx];
    const key = Math.round(ndLat * 20) + "," + Math.round(ndLon * 20) + "," + ndRangeIdx;
    if (key !== ndNavAidsCacheKey) {
        ndNavAidsCacheKey = key;
        ndNavAidsNear = ndNearbyPoints(ndNavAids, function (v) { return true; });
    }
    ctx.font = "22px Arial";
    ctx.strokeStyle = ndTheme.nd.navaids;
    ctx.fillStyle = ndTheme.nd.navaids;
    ctx.lineWidth = 2;
    ctx.textAlign = "left";
    var drawn = 0;
    for (const v of ndNavAidsNear) {
        const p = ndProject(v.lat, v.lon, geom, ppnm);
        if (p.dist > range) {
            continue;
        }
        // Hexagon, flat sides top and bottom
        const r = 10;
        ctx.beginPath();
        for (var i = 0; i < 6; i++) {
            const angle = Math.PI / 6 + i * Math.PI / 3;
            const x = p.x + r * Math.cos(angle);
            const y = p.y + r * Math.sin(angle);
            if (i === 0) {
                ctx.moveTo(x, y);
            } else {
                ctx.lineTo(x, y);
            }
        }
        ctx.closePath();
        ctx.stroke();
        ctx.fillRect(p.x - 2, p.y - 2, 4, 4);
        ctx.fillText(v.n, p.x + 14, p.y + 8);
        if (++drawn >= 40) {
            break;
        }
    }
}

