function setNDWeatherPath(path) {
    // The RainViewer API returns the path WITH a leading slash ("/v2/radar/..."), and
    // a double slash in the tile URL 404s (verified against the live server - Cesium's
    // rain layer gets away with it only because its Resource class normalises URLs)
    if (path !== undefined) {
        path = path.replace(/^\/+/, "");
    }
    if (path !== ndWxPath) {
        ndWxPath = path;
        ndWxTiles.clear(); // A new frame: every cached tile is stale
    }
}


// Shared bounding-box pre-filter for the static overlay databases (airports,
// navaids): everything passing `keep` within a box slightly larger than the range
// circle, so a cached result stays valid while the aircraft moves a little
function ndNearbyPoints(points, keep) {
    const range = ndRanges[ndRangeIdx];
    const maxLatDiff = range / 60 * 1.3;
    const maxLonDiff = maxLatDiff / Math.max(0.2, Math.cos(ndLat * Math.PI / 180));
    const near = [];
    for (const p of points) {
        if (keep(p) && (Math.abs(p.lat - ndLat) <= maxLatDiff)) {
            var lonDiff = Math.abs(p.lon - ndLon);
            if (lonDiff > 180) {
                lonDiff = 360 - lonDiff;
            }
            if (lonDiff <= maxLonDiff) {
                near.push(p);
            }
        }
    }
    return near;
}

// The compass rose is magnetic (ndHeading), but waypoint and traffic bearings are
// computed from true positions, so the overlay is off by local magnetic declination.
// Accepted for now - fixing it needs declination sent as an entity property
function ndReferenceHeading() {
    return ndHeading !== undefined ? ndHeading : (ndTrack !== undefined ? ndTrack : 0);
}

function ndGeometry() {
    if (ndMode === 1) {
        return { refX: 500, refY: 770, radius: 620 };
    } else {
        return { refX: 500, refY: 520, radius: 400 };
    }
}

// Project latitude/longitude to canvas coordinates, heading up around own position
// Equirectangular approximation - fine for ND ranges
function ndProject(lat, lon, geom, ppnm) {
    const dN = (lat - ndLat) * 60.0;
    const dE = (lon - ndLon) * 60.0 * Math.cos(ndLat * Math.PI / 180.0);
    const h = ndReferenceHeading() * Math.PI / 180.0;
    return {
        x: geom.refX + (dE * Math.cos(h) - dN * Math.sin(h)) * ppnm,
        y: geom.refY - (dN * Math.cos(h) + dE * Math.sin(h)) * ppnm,
        dist: Math.sqrt(dN * dN + dE * dE)
    };
}

function ndDrawWaypointSymbol(ctx, x, y, size) {
    // 4 pointed star
    const inner = size * 0.25;
    ctx.beginPath();
    ctx.moveTo(x, y - size);
    ctx.lineTo(x + inner, y - inner);
    ctx.lineTo(x + size, y);
    ctx.lineTo(x + inner, y + inner);
    ctx.lineTo(x, y + size);
    ctx.lineTo(x - inner, y + inner);
    ctx.lineTo(x - size, y);
    ctx.lineTo(x - inner, y - inner);
    ctx.closePath();
    ctx.stroke();
}

function ndDrawFlightPlan(ctx, geom, ppnm) {
    if ((ndFlightPlan === undefined) || (ndLat === undefined) || (ndLon === undefined)) {
        return;
    }
    const wpts = ndFlightPlan.wpts;
    if (!wpts || (wpts.length === 0)) {
        return;
    }
    const act = ndFlightPlan.act;

    // Project the waypoints that have positions, keeping their index for active leg colouring
    var placed = [];
    for (var i = 0; i < wpts.length; i++) {
        if ((wpts[i].lat !== undefined) && (wpts[i].lon !== undefined)) {
            placed.push({ i: i, p: ndProject(wpts[i].lat, wpts[i].lon, geom, ppnm), wp: wpts[i] });
        }
    }

    const T = ndTheme.nd;
    ctx.lineWidth = 3;
    for (var j = 1; j < placed.length; j++) {
        // Airbus: the leg to the active waypoint is white, the rest of the route green.
        // Boeing: the whole route magenta
        ctx.strokeStyle = (placed[j].i === act) ? T.activeRoute : T.route;
        ctx.beginPath();
        ctx.moveTo(placed[j - 1].p.x, placed[j - 1].p.y);
        ctx.lineTo(placed[j].p.x, placed[j].p.y);
        ctx.stroke();
    }

    ctx.font = "24px Arial";
    ctx.textAlign = "left";
    ctx.lineWidth = 3;
    for (const pw of placed) {
        const color = (pw.i === act) ? T.activeWaypoint : T.waypoint;
        ctx.strokeStyle = color;
        ctx.fillStyle = color;
        ndDrawWaypointSymbol(ctx, pw.p.x, pw.p.y, 14);
        if (pw.wp.n !== undefined) {
            ctx.fillText(pw.wp.n, pw.p.x + 18, pw.p.y - 12);
        }
    }
}

function ndDrawRangeRings(ctx, geom) {
    ctx.strokeStyle = "white";
    ctx.lineWidth = 2;
    // Airbus draws the range rings as dashes, Boeing as solid lines
    ctx.setLineDash((ndTheme.nd.rangeRings === "dashed") ? [16, 14] : []);
    for (var i = 1; i <= 3; i++) {
        ctx.beginPath();
        if (ndMode === 1) {
            // Only the part of the arc that is on the canvas
            ctx.arc(geom.refX, geom.refY, geom.radius * i / 4, -Math.PI * 0.85, -Math.PI * 0.15);
        } else {
            ctx.arc(geom.refX, geom.refY, geom.radius * i / 4, 0, 2 * Math.PI);
        }
        ctx.stroke();
    }
    ctx.setLineDash([]);

    // Label the half range ring
    const halfRange = ndRanges[ndRangeIdx] / 2;
    const labelAngle = (ndMode === 1) ? -25 : -45; // Degrees from up
    const a = (labelAngle - 90) * Math.PI / 180.0;
    ctx.fillStyle = ndTheme.nd.rangeLabel;
    ctx.font = "24px Arial";
    ctx.textAlign = "center";
    ctx.fillText(halfRange.toString(), geom.refX + geom.radius * 0.5 * Math.cos(a), geom.refY + geom.radius * 0.5 * Math.sin(a) - 6);
}

// The radius at which the graduations end - Airbus ticks point outwards from the
// compass ring, so the lubber line and the selected heading bug sit outside them
function ndCompassOuter(geom) {
    return geom.radius + ((ndTheme.nd.compassTicks === "outward") ? 24 : 0);
}

function ndDrawCompass(ctx, geom) {
    const refHdg = ndReferenceHeading();

    // Compass ring
    ctx.strokeStyle = "white";
    ctx.lineWidth = 3;
    ctx.beginPath();
    if (ndMode === 1) {
        ctx.arc(geom.refX, geom.refY, geom.radius, -Math.PI * 0.85, -Math.PI * 0.15);
    } else {
        ctx.arc(geom.refX, geom.refY, geom.radius, 0, 2 * Math.PI);
    }
    ctx.stroke();

    // Ticks and numerals, rotated with the rose
    ctx.save();
    ctx.translate(geom.refX, geom.refY);
    ctx.rotate(-refHdg * Math.PI / 180.0);
    ctx.font = "30px Arial";
    ctx.textAlign = "center";
    ctx.lineWidth = 3;
    const outward = (ndTheme.nd.compassTicks === "outward");
    for (var deg = 0; deg < 360; deg += 5) {
        ctx.save();
        ctx.rotate(deg * Math.PI / 180.0);
        const len = ((deg % 10) === 0) ? 24 : 12;
        ctx.beginPath();
        ctx.moveTo(0, -geom.radius);
        ctx.lineTo(0, outward ? -geom.radius - len : -geom.radius + len);
        ctx.stroke();
        if ((deg % 30) === 0) {
            ctx.fillStyle = "white";
            // Airbus: numerals outside, beyond the graduations. Boeing: inside the ring
            ctx.fillText((deg / 10).toString(), 0, outward ? -geom.radius - 30 : -geom.radius + 58);
        }
        ctx.restore();
    }
    ctx.restore();

    // Lubber line
    const T = ndTheme.nd;
    ctx.strokeStyle = T.lubber;
    ctx.lineWidth = 4;
    const outerRadius = ndCompassOuter(geom);
    ctx.beginPath();
    ctx.moveTo(geom.refX, geom.refY - outerRadius - 15);
    ctx.lineTo(geom.refX, geom.refY - geom.radius + 40);
    ctx.stroke();
    if (ndMode === 0) {
        // Tail of the lubber line in ROSE mode
        ctx.beginPath();
        ctx.moveTo(geom.refX, geom.refY + geom.radius - 40);
        ctx.lineTo(geom.refX, geom.refY + outerRadius + 15);
        ctx.stroke();
    }

    // Heading readout above the lubber line
    if ((ndHeading !== undefined) || (ndTrack !== undefined)) {
        const hdgText = pad(Math.round(ndReferenceHeading()) % 360, 3);
        if (T.headingBox === "boeing") {
            // Boeing: HDG in green, the digits boxed in white, MAG in green
            ctx.fillStyle = "black";
            ctx.fillRect(geom.refX - 50, geom.refY - geom.radius - 70, 100, 50);
            ctx.strokeStyle = "white";
            ctx.lineWidth = 2;
            ctx.strokeRect(geom.refX - 50, geom.refY - geom.radius - 70, 100, 50);
            ctx.fillStyle = "white";
            ctx.font = "40px Arial";
            ctx.textAlign = "center";
            ctx.fillText(hdgText, geom.refX, geom.refY - geom.radius - 30);
            ctx.fillStyle = greenColor;
            ctx.font = "26px Arial";
            ctx.textAlign = "right";
            ctx.fillText("HDG", geom.refX - 60, geom.refY - geom.radius - 34);
            ctx.textAlign = "left";
            ctx.fillText("MAG", geom.refX + 60, geom.refY - geom.radius - 34);
        } else {
            ctx.fillStyle = "black";
            ctx.fillRect(geom.refX - 55, geom.refY - geom.radius - 70, 110, 50);
            ctx.strokeStyle = grayColor;
            ctx.lineWidth = 2;
            ctx.strokeRect(geom.refX - 55, geom.refY - geom.radius - 70, 110, 50);
            ctx.fillStyle = "white";
            ctx.font = "40px Arial";
            ctx.textAlign = "center";
            ctx.fillText(hdgText, geom.refX, geom.refY - geom.radius - 30);
        }
    }
}

function ndDrawTrack(ctx, geom) {
    if ((ndTrack === undefined) || (ndHeading === undefined)) {
        return;
    }
    const rel = (ndTrack - ndReferenceHeading()) * Math.PI / 180.0;
    const T = ndTheme.nd;
    ctx.save();
    ctx.translate(geom.refX, geom.refY);
    ctx.rotate(rel);
    ctx.strokeStyle = T.track;
    ctx.lineWidth = 3;
    const diamondY = -geom.radius + 60;
    ctx.beginPath();
    if (T.trackDiamond) {
        ctx.moveTo(0, 0);
        ctx.lineTo(0, diamondY + 14);
        ctx.moveTo(0, diamondY - 14);
        ctx.lineTo(0, -geom.radius);
        ctx.stroke();
        // Open diamond on the track line, just inside the compass
        ctx.beginPath();
        ctx.moveTo(0, diamondY - 14);
        ctx.lineTo(10, diamondY);
        ctx.lineTo(0, diamondY + 14);
        ctx.lineTo(-10, diamondY);
        ctx.closePath();
        ctx.stroke();
    } else {
        // Boeing: a plain line, with range marks along it
        ctx.moveTo(0, 0);
        ctx.lineTo(0, -geom.radius);
        for (var i = 1; i <= 3; i++) {
            ctx.moveTo(-8, -geom.radius * i / 4);
            ctx.lineTo(8, -geom.radius * i / 4);
        }
        ctx.stroke();
    }
    ctx.restore();
}

function ndDrawSelectedHeading(ctx, geom) {
    if (ndSelectedHeading === undefined) {
        return;
    }
    var rel = ndSelectedHeading - ndReferenceHeading();
    while (rel > 180) rel -= 360;
    while (rel < -180) rel += 360;
    const T = ndTheme.nd;
    if ((ndMode === 1) && (Math.abs(rel) > 55)) {
        // Off the arc - show the selected value at the nearer end
        ctx.fillStyle = T.selectedHeading;
        ctx.font = "30px Arial";
        ctx.textAlign = (rel > 0) ? "right" : "left";
        const a = ((rel > 0 ? 55 : -55) - 90) * Math.PI / 180.0;
        ctx.fillText(pad(Math.round(ndSelectedHeading) % 360, 3), geom.refX + geom.radius * Math.cos(a), geom.refY + geom.radius * Math.sin(a));
        return;
    }
    ctx.save();
    ctx.translate(geom.refX, geom.refY);
    ctx.rotate(rel * Math.PI / 180.0);
    ctx.strokeStyle = T.selectedHeading;
    ctx.lineWidth = 3;
    const outer = ndCompassOuter(geom);
    if (T.selectedHeadingLine) {
        // Boeing: a dashed line from own ship out to the bug
        ctx.setLineDash([12, 10]);
        ctx.beginPath();
        ctx.moveTo(0, 0);
        ctx.lineTo(0, -geom.radius);
        ctx.stroke();
        ctx.setLineDash([]);
        // and the bug is a hollow trapezoid riding the outside of the compass
        ctx.beginPath();
        ctx.moveTo(-16, -outer - 20);
        ctx.lineTo(-8, -outer);
        ctx.lineTo(8, -outer);
        ctx.lineTo(16, -outer - 20);
        ctx.closePath();
        ctx.stroke();
    } else {
        // Chevron just outside the compass
        ctx.beginPath();
        ctx.moveTo(-14, -outer - 20);
        ctx.lineTo(0, -outer);
        ctx.lineTo(14, -outer - 20);
        ctx.stroke();
    }
    ctx.restore();
}

